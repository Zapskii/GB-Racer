; raster.s - the road scanline ISR and the per-frame SCX table builder
;
; ============================================================================
; _road_isr  -  HBlank interrupt, installed straight on the STAT vector ($48)
; ============================================================================
; Bypasses GBDK's ISR dispatcher (a C handler would cost 80+ cycles of
; prologue/epilogue per line).  Fires at the start of HBlank on every visible
; line while LCD-STAT is enabled in IE (main.c: the timer gates it around the
; road region).
;
; Two independent page pointers, both indexed by LY:
;     tbl_page : WRAM double-buffer, SCX for line LY+1  (built every frame)
;     bgp_page : BGP for line LY+1.  Normally one of the 16 stripe rows in ROM
;                (pat_rows, generated by tools/gen_road.py), so choosing the
;                stripe phase costs nothing per frame.
; Both live in HRAM so they can be read with the 3-cycle ldh.
;
; Cost: 5 (dispatch) + 4 (the vector's jp) + 40 = 49 M-cycles per line.  The
; last register write (BGP) lands ~39 M-cycles after HBlank starts, so it must
; complete inside HBlank plus the next line's OAM scan.  Keep sprites on road
; lines to ~6.
;
; ============================================================================
; _build_tables_asm  -  fills the SCX back buffer for one frame (~750 M-cycles)
; ============================================================================
; Parameters are passed in globals (set by build_tables_fast() in main.c):
;     bt_s      u16  initial scroll position, 8.8 px: SCX_BASE*256 + cam
;     bt_ds     s16  its slope per line, 8.8 px/line  (zero at the horizon)
;     bt_curve  s16  change of slope per 8-line chunk, 8.8 px/line
;     bt_scx    ptr  &scx_table[IDX0 + 79]   (bottom road line; we walk upward)
;
; One line = 6 cycles.  DE walks the table, HL is the scroll position (its
; high byte *is* SCX), BC is the slope; "add hl,bc" does the whole accumulator
; step.  Unrolled 8x; the curve is applied once per chunk.

        .include        "global.s"

        .globl  _bt_s
        .globl  _bt_ds
        .globl  _bt_curve
        .globl  _bt_scx

        .area   _HRAM
_tbl_page::
        .ds     1
_bgp_page::
        .ds     1

        .area   _CODE

_road_isr::
        push    af                  ; 4
        push    hl                  ; 4
        ldh     a,(.LY)             ; 3   current line (HBlank of line LY)
        ld      l,a                 ; 1
        ldh     a,(_tbl_page)       ; 3   high byte of the active SCX table
        ld      h,a                 ; 1
        ld      a,(hl)              ; 2
        ldh     (.SCX),a            ; 3
        ldh     a,(_bgp_page)       ; 3   high byte of the active BGP row
        ld      h,a                 ; 1
        ld      a,(hl)              ; 2
        ldh     (.BGP),a            ; 3
        pop     hl                  ; 3
        pop     af                  ; 3
        reti                        ; 4


_build_tables_asm::
        push    bc
        push    de
        push    hl

        ; ---- load parameters --------------------------------------------
        ld      a,(_bt_s)
        ld      l,a
        ld      a,(_bt_s+1)
        ld      h,a
        ld      a,(_bt_ds)
        ld      c,a
        ld      a,(_bt_ds+1)
        ld      b,a
        ld      a,(_bt_scx)
        ld      e,a
        ld      a,(_bt_scx+1)
        ld      d,a

        ; ---- SCX, 80 lines bottom -> horizon, 10 chunks of 8 ---------------
1$:
        ld      a,h                 ; line 1
        ld      (de),a
        add     hl,bc
        dec     e
        ld      a,h                 ; line 2
        ld      (de),a
        add     hl,bc
        dec     e
        ld      a,h                 ; line 3
        ld      (de),a
        add     hl,bc
        dec     e
        ld      a,h                 ; line 4
        ld      (de),a
        add     hl,bc
        dec     e
        ld      a,h                 ; line 5
        ld      (de),a
        add     hl,bc
        dec     e
        ld      a,h                 ; line 6
        ld      (de),a
        add     hl,bc
        dec     e
        ld      a,h                 ; line 7
        ld      (de),a
        add     hl,bc
        dec     e
        ld      a,h                 ; line 8
        ld      (de),a
        add     hl,bc
        dec     e

        ld      a,(_bt_curve)       ; slope += curve   (once per chunk)
        add     a,c
        ld      c,a
        ld      a,(_bt_curve+1)
        adc     a,b
        ld      b,a

        ld      a,e                 ; done when E has walked down to IDX0-1 (46)
        cp      a,#46
        jr      nz,1$

        pop     hl
        pop     de
        pop     bc
        ret
