"""
Generates src/hud_data.c / src/hud_data.h: a small 5x7 font as Game Boy tiles for the HUD
(window layer).  Glyph pixels are colour 0 (white) on colour 3 (black), so the HUD reads as
white text on the black strip at the bottom of the screen.

Glyph order == tile order; src/hud.c maps characters to tiles with the F_* constants.
Importable: `from gen_hud import GLYPHS, CHARS` gives the char -> index map for the tests.
"""
