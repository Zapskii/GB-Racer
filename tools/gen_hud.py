CHARS = list(GLYPHS)                       # index in this list == tile index in hud_font

def encode(rows):
    """7 rows of 5 chars -> 16-byte tile: 1px left margin, row 7 blank, glyph = colour 0 on colour 3."""
    out = []
    for y in range(8):
        lo = hi = 0
        for x in range(8):
            on = y < 7 and 1 <= x <= 5 and rows[y][x - 1] == "#"
            c = 0 if on else 3
            lo |= (c & 1) << (7 - x)
            hi |= ((c >> 1) & 1) << (7 - x)
        out += [lo, hi]
    return out

def main():
    out_dir = Path(sys.argv[1])
    out_dir.mkdir(parents=True, exist_ok=True)
    data = [b for ch in CHARS for b in encode(GLYPHS[ch])]
    c = '/* GENERATED by tools/gen_hud.py - do not edit */\n#pragma bank 1   /* boot-time data: lives in ROM bank 1 (read once at start-up, before a track palette bank is selected) */\n#include "hud_data.h"\n\n'
    c += f"const unsigned char hud_font[{len(data)}] = {{\n"
    for i in range(0, len(data), 16):
        c += "    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n"
    c += "};\n"
    (out_dir / "hud_data.c").write_text(c)
    t = '/* GENERATED by tools/gen_hud.py - do not edit */\n#include "hud_data.h"\n\n'
    t += "const char hud_chars[] = \"" + "".join(CHARS) + "\";   /* tile index = position in this string */\n"
    (out_dir / "hud_tab.c").write_text(t)
    names = {" ": "SPACE", ":": "COLON", ".": "DOT", "-": "DASH", "!": "BANG", "/": "SLASH", "<": "LT", ">": "GT"}
    h = "/* GENERATED by tools/gen_hud.py - do not edit */\n#ifndef HUD_DATA_H\n#define HUD_DATA_H\n\n"
    h += f"#define HUD_GLYPHS {len(CHARS)}\n"
    for i, ch in enumerate(CHARS):
        if ch.isdigit():
            continue
        h += f"#define F_{names.get(ch, ch)} {i}\n"
    h += f"#define F_DIGIT0 {CHARS.index('0')}   /* digits are consecutive */\n"
    h += "\nextern const unsigned char hud_font[];\nextern const char hud_chars[];\n\n#endif\n"
    (out_dir / "hud_data.h").write_text(h)
    print(f"hud glyph tiles: {len(CHARS)}")

if __name__ == "__main__":
    main()
