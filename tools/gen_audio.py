#!/usr/bin/env python3
"""
Generates src/audio_data.c / audio_data.h: the tune, the frequency tables, the wave table and the
engine-pitch ladder for src/audio.c.

Song (A minor, one row = ROW_FRAMES frames = an eighth note, 8 rows per bar, 8 bars, loops):
    lead     channel 1 (pulse 25%)      riff over Am Am F F C C G G
    harmony  channel 2 (pulse 50%)      quiet chord arpeggio       (muted while the lap jingle plays)
    bass     channel 3 (triangle wave)  driving eighths, root and octave
Sound effects: engine drone on channel 4 (7-bit noise = a tonal buzz, pitch follows speed),
gravel hiss when off the road, crash burst; lap / countdown / finish jingles on channel 2 (SFX table).

A track is a list of (note, rows) pairs, note = MIDI number or 0 for a rest, ended by 0xFF.
Frequency tables: pulse register value x = 2048 - 131072/f, wave x = 2048 - 65536/f.

Usage: gen_audio.py <output_dir>
"""
import math
import sys
from pathlib import Path

ROW_FRAMES = 7
NOTE0, NOTE1 = 36, 96            # MIDI range covered by the tables (C2 .. C7)

def hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)

def pulse_x(m):
    return round(2048 - 131072 / hz(m))

def wave_x(m):
    return round(2048 - 65536 / hz(m))

CHORDS = [  # (root pitch class MIDI at octave 2, third offset)
    (45, 3), (45, 3), (41, 4), (41, 4), (48, 4), (48, 4), (43, 4), (43, 4),
]
LEAD_BARS = [
    [(76, 2), (74, 1), (72, 1), (69, 2), (72, 2)],
    [(76, 1), (79, 1), (76, 2), (74, 2), (72, 2)],
    [(77, 2), (76, 1), (72, 1), (69, 2), (72, 2)],
    [(77, 1), (81, 1), (77, 2), (76, 2), (72, 2)],
    [(79, 2), (76, 1), (72, 1), (67, 2), (72, 2)],
    [(79, 1), (84, 1), (79, 2), (76, 2), (72, 2)],
    [(74, 2), (71, 1), (67, 1), (62, 2), (67, 2)],
    [(74, 1), (79, 1), (74, 2), (71, 2), (76, 2)],
]

def build_tracks():
    lead, harm, bass = [], [], []
    for bar, (root, third) in enumerate(CHORDS):
        assert sum(n for _, n in LEAD_BARS[bar]) == 8, bar
        lead += LEAD_BARS[bar]
        for step in (0, 1, 2, 3, 0, 1, 2, 3):
            harm.append((root + 12 + [0, third, 7, third][step], 1))
        for step in (0, 0, 12, 0, 0, 0, 12, 0):
            bass.append((root + step, 1))
    return lead, harm, bass

# sound effects on channel 2: (name, MIDI notes, frames per note, frames the last note is held)
SFX = [
    ("LAP",    [72, 76, 79, 84],            6, 18),     # lap done: C E G C
    ("BEEP",   [69],                       14, 14),     # countdown 3, 2, 1
    ("GO",     [81],                       36, 36),     # countdown GO: higher and longer
    ("FINISH", [72, 76, 79, 84, 79, 84, 88], 6, 36),    # the flag
]

def ladder():
    """Eight 7-bit-noise settings (NR43 values) from ~40 Hz to ~220 Hz of drone pitch, closest (shift, divider)."""
    out = []
    for i in range(8):
        f = 40 * (5.5 ** (i / 7))
        target = 262144 / (127 * f)                      # wanted r * 2^s
        best = None
        for s in range(0, 8):
            for r in range(0, 8):
                d = (0.5 if r == 0 else r) * 2 ** s
                err = abs(math.log(d / target))
                if best is None or err < best[0]:
                    best = (err, s, r)
        out.append((best[1] << 4) | 0x08 | best[2])
    return out

def tri_wave():
    nib = list(range(16)) + list(range(15, -1, -1))     # 32 samples
    return [(nib[2 * i] << 4) | nib[2 * i + 1] for i in range(16)]

def arr(name, data, typ="const unsigned char", per=16, fmt="0x%02X"):
    s = f"{typ} {name}[{len(data)}] = {{\n"
    for i in range(0, len(data), per):
        s += "    " + ", ".join(fmt % v for v in data[i:i + per]) + ",\n"
    return s + "};\n\n"

def enc(track):
    out = []
    for n, r in track:
        assert n == 0 or NOTE0 <= n < NOTE1, n
        out += [n - NOTE0 + 1 if n else 0, r]
    return out + [0xFF]

def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    lead, harm, bass = build_tracks()
    c = '/* GENERATED by tools/gen_audio.py - do not edit */\n#include "audio_data.h"\n\n'
    c += arr("mus_lead", enc(lead)) + arr("mus_harm", enc(harm)) + arr("mus_bass", enc(bass))
    # tables are indexed by (note - NOTE0 + 1); entry 0 is unused
    c += arr("pulse_freq", [0] + [pulse_x(m) for m in range(NOTE0, NOTE1)], "const unsigned int", 8, "0x%04X")
    c += arr("wave_freq", [0] + [wave_x(m) for m in range(NOTE0, NOTE1)], "const unsigned int", 8, "0x%04X")
    c += arr("wave_ram", tri_wave())
    c += arr("eng_nr43", ladder())
    c += arr("sfx_notes", [m - NOTE0 + 1 for _, notes, _, _ in SFX for m in notes])
    offs = [0]
    for _, notes, _, _ in SFX:
        offs.append(offs[-1] + len(notes))
    c += arr("sfx_off", offs) + arr("sfx_step", [st for _, _, st, _ in SFX]) + arr("sfx_hold", [h for _, _, _, h in SFX])
    h = "/* GENERATED by tools/gen_audio.py - do not edit */\n#ifndef AUDIO_DATA_H\n#define AUDIO_DATA_H\n\n"
    h += f"#define ROW_FRAMES {ROW_FRAMES}      /* frames per music row (an eighth note) */\n"
    h += f"#define NOTE0 {NOTE0}\n"
    for i, (name, _, _, _) in enumerate(SFX):
        h += f"#define SFX_{name} {i}\n"
    h += "\n"
    for n in ("mus_lead", "mus_harm", "mus_bass", "wave_ram", "eng_nr43", "sfx_notes", "sfx_off", "sfx_step", "sfx_hold"):
        h += f"extern const unsigned char {n}[];\n"
    h += "extern const unsigned int pulse_freq[];\nextern const unsigned int wave_freq[];\n\n#endif\n"
    (out / "audio_data.c").write_text(c)
    (out / "audio_data.h").write_text(h)
    print(f"music: lead {len(lead)} notes, harmony {len(harm)}, bass {len(bass)}; "
          f"{len(lead) and sum(r for _, r in lead)} rows = {sum(r for _, r in lead) * ROW_FRAMES / 60:.1f} s per loop")
    print("engine NR43 ladder:", [hex(v) for v in ladder()])

if __name__ == "__main__":
    main()
